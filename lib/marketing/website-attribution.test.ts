import { describe, expect, it } from "vitest";
import { parseWebsiteAttribution, websiteAttributionFromParams, websiteAttributionNote } from "./website-attribution";

describe("website campaign attribution", () => {
  it("round-trips the quote links generated by the Marketing Desk", () => {
    const attribution = websiteAttributionFromParams(new URLSearchParams("utm_source=facebook_instagram&utm_medium=social&utm_campaign=job_window-cleaning"));
    expect(websiteAttributionNote(attribution)).toBe("Website campaign (visitor-supplied): facebook_instagram / social / job_window-cleaning");
  });
  it.each([null, "google", [], { source: true }, { source: "x".repeat(101) }, { source: "google\nForged note" }, { source: "person@example.com" }])("rejects invalid or private source labels", (value) => {
    expect(parseWebsiteAttribution(value)).toBeNull();
  });
  it("keeps attribution optional for ordinary requests", () => {
    expect(websiteAttributionFromParams(new URLSearchParams())).toBeNull();
    expect(websiteAttributionNote(null)).toBeNull();
  });
  it("drops invalid optional labels without blocking a valid source", () => {
    expect(parseWebsiteAttribution({ source: "google", medium: { malicious: true }, campaign: "<script>" })).toEqual({ source: "google", medium: null, campaign: null });
  });
});
